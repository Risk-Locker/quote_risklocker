def wrap_cursor_mdc(description: str, globs: str, source_file: Path) -> str:
    body = source_file.read_text(encoding="utf-8-sig").strip()
    return (
        "---\n"
        f"description: {description}\n"
        f"globs: {globs}\n"
        "alwaysApply: false\n"
        "---\n\n"
        f"<!-- Synced from {source_file.relative_to(ROOT).as_posix()} -->\n\n"
        f"{body}\n"
    )


def is_reparse_or_link(path: Path) -> bool:
    if path.is_symlink():
        return True
    try:
        return bool(os.lstat(path).st_file_attributes & 0x0400)  # FILE_ATTRIBUTE_REPARSE_POINT
    except (AttributeError, OSError):
        return False


def remove_link_or_dir(path: Path) -> None:
    if not path.exists() and not path.is_symlink() and not is_reparse_or_link(path):
        return
    if is_reparse_or_link(path):
        try:
            path.rmdir()
        except OSError:
            path.unlink()
        return
    if path.is_file():
        path.unlink()
        return
    # Remove children safely first so inner reparse junctions never get recursively deleted
    for child in list(path.iterdir()):
        remove_link_or_dir(child)
    path.rmdir()


def ensure_dir_link(link_path: Path, target_dir: Path, *, write: bool, drift: list[str]) -> None:
    expected_resolved = target_dir.resolve()
    if is_reparse_or_link(link_path):
        try:
            if link_path.resolve() == expected_resolved:
                return
        except OSError:
            pass
    elif link_path.exists():
        # Existing real folder instead of zero-copy link
        pass

    rel = link_path.relative_to(ROOT).as_posix()
    if not write:
        drift.append(f"Workstation directory link stale/not linked: {rel} -> {target_dir.relative_to(ROOT).as_posix()}")
        return

    remove_link_or_dir(link_path)
    link_path.parent.mkdir(parents=True, exist_ok=True)
    if os.name == "nt":
        proc = subprocess.run(
            ["cmd", "/c", "mklink", "/J", str(link_path), str(target_dir.resolve())],
            capture_output=True,
            text=True,
        )
        if proc.returncode != 0:
            raise RuntimeError(f"Failed creating NTFS junction {link_path}: {proc.stderr or proc.stdout}")
    else:
        os.symlink(os.path.relpath(target_dir, link_path.parent), link_path, target_is_directory=True)


def sync_text_file(target: Path, expected: str, *, write: bool, drift: list[str]) -> None:
    rel = target.relative_to(ROOT).as_posix()
    current = target.read_text(encoding="utf-8") if target.exists() else None
    normalized_expected = expected.replace("\r\n", "\n")
    normalized_current = current.replace("\r\n", "\n") if current is not None else None
    if normalized_current == normalized_expected:
        return
    if not write:
        drift.append(f"Drift in adapter: {rel}")
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(normalized_expected, encoding="utf-8")


def audit_stale_copies_and_links(*, clean: bool, drift: list[str]) -> None:
    """Detect duplicated legacy copies or dangling junctions inside .claude/ and .cursor/."""
    for folder in [ROOT / ".claude" / "skills", ROOT / ".cursor" / "skills"]:
        if not folder.exists() and not is_reparse_or_link(folder):
            continue
        if is_reparse_or_link(folder):
            # Single top-level junction pointing to .agents/skills is valid zero-copy design
            try:
                if folder.resolve() != (ROOT / ".agents" / "skills").resolve():
                    if clean:
                        remove_link_or_dir(folder)
                    else:
                        drift.append(f"Broken top-level junction: {folder.relative_to(ROOT).as_posix()}")
            except OSError:
                if clean:
                    remove_link_or_dir(folder)
                else:
                    drift.append(f"Broken top-level junction: {folder.relative_to(ROOT).as_posix()}")
            continue

        for entry in list(folder.iterdir()):
            if entry.is_dir() and (entry / MARKER_FILE).exists():
                if clean:
                    remove_link_or_dir(entry)
                else:
                    drift.append(f"Legacy copied skill mirror (should be zero-copy): {entry.relative_to(ROOT).as_posix()}")
            elif is_reparse_or_link(entry) and not entry.exists():
                if clean:
                    remove_link_or_dir(entry)
                else:
                    drift.append(f"Dangling skill junction: {entry.relative_to(ROOT).as_posix()}")


def _parse_manifest_roles() -> tuple[dict[str, dict[str, object]], list[str]]:
    """Parse `.agents/manifest.yaml` `roles:` entries without third-party PyYAML."""
    manifest_file = ROOT / ".agents" / "manifest.yaml"
    if not manifest_file.exists():
        return {}, [".agents/manifest.yaml not found"]

    roles: dict[str, dict[str, object]] = {}
    in_roles = False
    cur_role: str | None = None
    for raw in manifest_file.read_text(encoding="utf-8-sig", errors="replace").splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        indent = len(raw) - len(raw.lstrip(" "))
        stripped = raw.strip()
        if indent == 0:
            in_roles = stripped == "roles:"
            cur_role = None
            continue
        if not in_roles:
            continue
        if indent == 2 and stripped.endswith(":"):
            cur_role = stripped[:-1].strip().strip("\"'")
            roles[cur_role] = {}
            continue
        if cur_role and indent >= 4:
            m = re.match(r"^([A-Za-z0-9_-]+)\s*:\s*(.*)$", stripped)
            if m:
                k, raw_v = m.group(1), m.group(2).strip().strip("\"'")
                if raw_v.lower() == "true":
                    roles[cur_role][k] = True
                elif raw_v.lower() == "false":
                    roles[cur_role][k] = False
                else:
                    roles[cur_role][k] = raw_v
    return roles, []


def _parse_bool_frontmatter(val: str) -> bool | None:
    low = val.strip().lower()
    if low == "true":
        return True
    if low == "false":
        return False
    return None


def audit_agent_definitions(drift: list[str]) -> None:
    """Validate `.agents/agents/*.md` frontmatter, tool contracts, and `manifest.yaml` parity."""
    agents_dir = ROOT / ".agents" / "agents"
    if not agents_dir.exists():
        return

    manifest_roles, manifest_errs = _parse_manifest_roles()
    drift.extend(manifest_errs)

    agent_files = sorted(agents_dir.glob("*.md"))
    disk_stems = {f.stem for f in agent_files}
    if manifest_roles:
        missing_in_manifest = sorted(disk_stems - set(manifest_roles.keys()))
        missing_on_disk = sorted(set(manifest_roles.keys()) - disk_stems)
        for name in missing_in_manifest:
            drift.append(f".agents/agents/{name}.md missing from .agents/manifest.yaml roles:")
        for name in missing_on_disk:
            drift.append(f".agents/manifest.yaml declares '{name}' missing in .agents/agents/")

    for agent_file in agent_files:
        rel = agent_file.relative_to(ROOT).as_posix()
        lines = agent_file.read_text(encoding="utf-8-sig", errors="replace").splitlines()
        if not lines or lines[0].strip() != "---":
            drift.append(f"{rel}: Missing YAML frontmatter opening '---'")
            continue
        end_idx = next((idx for idx in range(1, len(lines)) if lines[idx].strip() == "---"), None)
        if end_idx is None:
            drift.append(f"{rel}: Unterminated YAML frontmatter")
            continue

        fm_lines = lines[1:end_idx]
        name_val = ""
        desc_val = ""
        model_val = ""
        main_agent_val: bool | None = None
        subagent_val: bool | None = None
        tools: list[str] = []
        in_tools = False
        for raw in fm_lines:
            stripped = raw.strip()
            if not stripped or stripped.startswith("#"):
                continue
            if raw.startswith((" ", "\t")) and in_tools and stripped.startswith("- "):
                tools.append(stripped[2:].strip().strip("\"'"))
                continue
            in_tools = False
            m = re.match(r"^([A-Za-z0-9_-]+)\s*:\s*(.*)$", stripped)
            if not m:
                continue
            key, val = m.group(1), m.group(2).strip().strip("\"'")
            if key == "name":
                name_val = val
            elif key == "description":
                desc_val = val
            elif key == "model":
                model_val = val
            elif key == "mainAgent":
                main_agent_val = _parse_bool_frontmatter(val)
            elif key == "subagent":
                subagent_val = _parse_bool_frontmatter(val)
            elif key == "tools":
                in_tools = True

        if name_val != agent_file.stem:
            drift.append(f"{rel}: Frontmatter name '{name_val}' != file stem '{agent_file.stem}'")
        if not desc_val:
            drift.append(f"{rel}: Missing non-empty YAML frontmatter 'description'")
        if model_val != "inherit":
            drift.append(f"{rel}: Model must be 'inherit' (got '{model_val or 'missing'}')")
        invalid_tools = [t for t in tools if t not in VALID_SUBAGENT_TOOLS]
        if invalid_tools:
            drift.append(f"{rel}: Unregistered/invalid subagent tool(s): {', '.join(invalid_tools)}")
        if agent_file.name.startswith(READ_ONLY_ROLE_PREFIXES):
            forbidden = [t for t in tools if t in READ_ONLY_MUTATING_TOOLS]
            if forbidden:
                drift.append(f"{rel}: Read-only governance role must not declare mutating tools: {', '.join(forbidden)}")

        role_cfg = manifest_roles.get(agent_file.stem)
        if role_cfg is not None:
            if role_cfg.get("recommended_model") != "inherit":
                drift.append(f".agents/manifest.yaml:{agent_file.stem} recommended_model must be 'inherit'")
            if main_agent_val != bool(role_cfg.get("main_agent", False)):
                drift.append(f"{rel}: mainAgent ({main_agent_val}) != manifest.yaml main_agent ({role_cfg.get('main_agent')})")
            if subagent_val != bool(role_cfg.get("subagent", True)):
                drift.append(f"{rel}: subagent ({subagent_val}) != manifest.yaml subagent ({role_cfg.get('subagent')})")

            has_write = any(t in READ_ONLY_MUTATING_TOOLS for t in tools)
            cfg_write = bool(role_cfg.get("enable_write_tools", False))
            if has_write != cfg_write:
                drift.append(f"{rel}: mutating tools ({has_write}) != manifest.yaml enable_write_tools ({cfg_write})")

            has_sub = any(t in SUBAGENT_DELEGATION_TOOLS for t in tools)
            cfg_sub = bool(role_cfg.get("enable_subagent_tools", False))
            if has_sub != cfg_sub:
                drift.append(f"{rel}: delegation tools ({has_sub}) != manifest.yaml enable_subagent_tools ({cfg_sub})")

            if role_cfg.get("enable_mcp_tools") is True:
                drift.append(
                    f".agents/manifest.yaml:{agent_file.stem} sets invalid enable_mcp_tools: true (static .md agents cannot declare call_mcp_tool; use mcp_delegation instead)"
                )


def clean_opt_in_ide_shims() -> None:
    for path in [ROOT / "CLAUDE.md", ROOT / ".claude", ROOT / ".cursor"]:
        if path.exists() or is_reparse_or_link(path):
            remove_link_or_dir(path)
    print("[PASS] Cleaned opt-in local IDE shims (CLAUDE.md, .claude/, .cursor/); .agents/ untouched.")


def run_sync(*, write: bool, ides: set[str]) -> int:
    drift: list[str] = []

    sync_text_file(
        ROOT / ".github" / "copilot-instructions.md",
        COPILOT_MD_CONTENT,
        write=write,
        drift=drift,
    )

    if "legacy-claude" in ides:
        sync_text_file(ROOT / "CLAUDE.md", CLAUDE_LEGACY_MD_CONTENT, write=write, drift=drift)
        ides.add("claude")

    if "claude" in ides:
        ensure_dir_link(ROOT / ".claude" / "skills", ROOT / ".agents" / "skills", write=write, drift=drift)
        ensure_dir_link(ROOT / ".claude" / "agents", ROOT / ".agents" / "agents", write=write, drift=drift)

    if "cursor" in ides:
        sync_text_file(ROOT / ".cursor" / "rules" / "00-core.mdc", cursor_rule_core(), write=write, drift=drift)
        subtree_specs = [
            ("10-backend.mdc", "Risklocker backend Python/FastAPI/worker/extraction rules", "backend/**/*.py,tests/**/*.py", ROOT / "backend" / "AGENTS.md"),
            ("20-frontend.mdc", "Risklocker Next.js/React/Tailwind UI and live canvas rules", "frontend/**/*.ts,frontend/**/*.tsx,frontend/**/*.css", ROOT / "frontend" / "AGENTS.md"),
            ("30-migrations.mdc", "Risklocker PostgreSQL migration and financial ledger schema rules", "migrations/**/*.sql", ROOT / "migrations" / "AGENTS.md"),
        ]
        for filename, desc, globs, src_path in subtree_specs:
            if src_path.exists():
                sync_text_file(
                    ROOT / ".cursor" / "rules" / filename,
                    wrap_cursor_mdc(desc, globs, src_path),
                    write=write,
                    drift=drift,
                )
        ensure_dir_link(ROOT / ".cursor" / "skills", ROOT / ".agents" / "skills", write=write, drift=drift)

    agent_errors: list[str] = []
    audit_stale_copies_and_links(clean=write, drift=drift)
    audit_agent_definitions(agent_errors)

    if agent_errors:
        print("[FAIL] Invalid .agents/agents/*.md definition(s):")
        for item in agent_errors:
            print(f"  - {item}")
        return 1

    if not write:
        if drift:
            print("[FAIL] Cross-IDE bridge / cleanliness check found issues:")
            for item in drift:
                print(f"  - {item}")
            print("Run: .\\.venv\\Scripts\\python.exe commands/sync-agent-bridges.py --write")
            return 1
        print("[PASS] Universal bridges (AGENTS.md + .github/copilot-instructions.md) and .agents/agents/*.md definitions clean; zero copied skill trees or dangling junctions.")
        return 0

    print("[PASS] Universal bridges synchronized and .agents/agents/*.md definitions verified.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Sync or check universal AI bridges from AGENTS.md and .agents/.")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="Write/sync tracked adapters (and any --ide opt-in links).")
    group.add_argument("--check", action="store_true", help="Verify adapters are in sync with zero duplicated/dangling shims.")
    group.add_argument("--clean-ide", action="store_true", help="Remove all opt-in local IDE shims (CLAUDE.md, .claude/, .cursor/).")
    parser.add_argument(
        "--ide",
        default="",
        help="Optional comma-separated local gitignored workstation shims: claude,cursor,legacy-claude",
    )
    args = parser.parse_args()

    if args.clean_ide:
        clean_opt_in_ide_shims()
        return 0

    ides = {item.strip().lower() for item in args.ide.split(",") if item.strip()}
    return run_sync(write=bool(args.write), ides=ides)


if __name__ == "__main__":
    raise SystemExit(main())
